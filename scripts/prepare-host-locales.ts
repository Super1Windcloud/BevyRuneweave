import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { execFileSync } from "node:child_process";

const root = resolve(import.meta.dirname, "..");
const rows = JSON.parse(readFileSync(resolve(root, "examples/host-localization.json"), "utf8")) as [string, string, string][];
const ids = new Set<string>(), keys = new Set<string>();
const placeholders = (value: string): string[] => [...value.matchAll(/\{([^{}]*)\}/g)].map((match, index) => match[1] || String(index));
for (const [id, en, zh] of rows) {
  if (!/^[a-z][a-z_0-9]*$/.test(id) || !en || !zh || ids.has(id) || keys.has(en)) throw new Error(`Invalid or duplicate host message: ${id}`);
  if (JSON.stringify(placeholders(en).sort()) !== JSON.stringify(placeholders(zh).sort())) throw new Error(`Host message parameters differ: ${id}`);
  ids.add(id); keys.add(en);
}
function write(path: string, value: string): void {
  const target = resolve(root, path);
  if (process.argv.includes("--check")) {
    if (readFileSync(target, "utf8") !== value) throw new Error(`Regenerate host localization: ${path}`);
    return;
  }
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, value);
}
const xml = (value: string): string => value.replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;").replaceAll("'", "\\'").replaceAll('"', '\\"').replaceAll("\n", "\\n");
function native(value: string, en: string, type: string): string {
  const parameters = placeholders(en);
  let index = 0;
  return value.replace(/\{([^{}]*)\}/g, (_, key: string) => {
    const parameter = key || String(index); index++;
    return `%${parameters.indexOf(parameter) + 1}$${type}`;
  });
}
for (const [language, column] of [["values", 1], ["values-zh", 2]] as const) {
  write(`examples/android-demo-host/app/src/main/res/${language}/strings.xml`, `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/prepare-host-locales.ts. -->\n<resources>\n${rows.map(([id, en, zh]) => `    <string name="host_${id}">${xml(native(column === 1 ? en : zh, en, "s"))}</string>`).join("\n")}\n</resources>\n`);
}
for (const [language, column] of [["en", 1], ["zh-Hans", 2]] as const) {
  write(`examples/ios-demo-host/Resources/${language}.lproj/Localizable.strings`, `/* Generated by scripts/prepare-host-locales.ts. */\n${rows.map(([, en, zh]) => `${JSON.stringify(en)} = ${JSON.stringify(native(column === 1 ? en : zh, en, "@"))};`).join("\n")}\n`);
}
const rust = `// Generated by scripts/prepare-host-locales.ts.\npub(super) const MESSAGES: &[(&str, &str)] = &[\n${[...rows].sort((a, b) => a[1] < b[1] ? -1 : 1).map(([, en, zh]) => `    (${JSON.stringify(en)}, ${JSON.stringify(zh)}),`).join("\n")}\n];\n\nmacro_rules! host_format {\n${rows.filter(([, en]) => en.includes("{")).map(([, en, zh]) => `    (${JSON.stringify(en)}, $($args:tt)*) => {\n        if crate::i18n::is_chinese() { format!(${JSON.stringify(zh)}, $($args)*) } else { format!(${JSON.stringify(en)}, $($args)*) }\n    };`).join("\n")}\n}\n`;
write("examples/desktop-demo-host/src/localized_messages.rs", execFileSync("rustfmt", ["--emit", "stdout", "--edition", "2024"], { input: rust, encoding: "utf8" }));
console.log(`${process.argv.includes("--check") ? "Verified" : "Prepared"} ${rows.length} English/Chinese host messages for Android, iOS and desktop.`);
