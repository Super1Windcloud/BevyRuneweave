import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { build } from "esbuild";
import { readPackFiles, safePath, sha256, zipFiles } from "./resource-packs.ts";

const project = resolve(import.meta.dirname, "..");
const assets = join(project, "modules/stk-car/game/assets");
const full = process.argv.includes("--full");
const manifestName = full ? "asset-manifest.json" : "startup-manifest.json";
const manifest = JSON.parse(readFileSync(join(assets, manifestName), "utf8")) as { files: string[] };
if (!Array.isArray(manifest.files) || manifest.files.some((path) => typeof path !== "string" || !safePath(path))) throw new Error(`Invalid ${manifestName}`);
const paths = [...new Set([...manifest.files, "engineConfig.json", "stk-car.js", "asset-manifest.json", "startup-manifest.json"])];
for (const file of paths) if (file !== "stk-car.js" && !existsSync(join(assets, file))) throw new Error(`Missing ${manifestName} asset ${file}`);
await build({ absWorkingDir: project, entryPoints: ["modules/stk-car/game/src/stk-car.ts"], outfile: join(assets, "stk-car.js"), bundle: true, format: "iife", target: "es2023" });
const archive = zipFiles(readPackFiles(assets, paths).map((file) => ({ path: `assets/${file.path}`, data: file.data })));
const output = resolve(project, "../../dist/stk-car"); mkdirSync(output, { recursive: true });
const name = full ? "stk-car-full.zip" : "stk-car.zip";
writeFileSync(join(output, name), archive);
writeFileSync(join(output, `${name}.sha256`), `${sha256(archive)}  ${name}\n`);
console.log(`${join(output, name)} — ${paths.length} files, ${(archive.length / 1024 ** 2).toFixed(2)} MiB`);
