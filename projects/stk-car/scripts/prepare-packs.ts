import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve, join } from "node:path";
import { packFor, readPackFiles, sha256, zipFiles, type ResourceCatalog } from "./resource-packs.ts";

const project = resolve(import.meta.dirname, "..");
const assets = join(project, "modules/stk-car/game/assets");
const output = resolve(project, "../../dist/stk-car/packs");
const tag = process.argv.find((arg) => arg.startsWith("--tag="))?.slice(6) ?? "stk-content-v1";
const baseUrl = `https://github.com/Super1Windcloud/BevyRuneweave/releases/download/${encodeURIComponent(tag)}`;
mkdirSync(output, { recursive: true });
const manifest = JSON.parse(readFileSync(join(assets, "asset-manifest.json"), "utf8")) as { files: string[] };
const groups = new Map<string, string[]>(), core: string[] = [];
for (const path of manifest.files) {
  const id = packFor(path);
  if (id === "source-local") continue;
  if (id) groups.set(id, [...groups.get(id) ?? [], path]); else core.push(path);
}
const catalog: ResourceCatalog = { schemaVersion: 1, packs: [], owners: {} };
const publication: { name: string; path: string; sha256: string; bytes: number }[] = [];
for (const [id, paths] of [...groups].sort(([a], [b]) => a.localeCompare(b))) {
  const files = readPackFiles(assets, [...new Set([...paths, "licenses/stk-assets.txt", "licenses/source-manifest.json"])]);
  const maxBytes = 512 * 1024 ** 2;
  if (files.length > 4096 || files.reduce((size, file) => size + file.data.length, 0) > maxBytes) throw new Error(`Pack exceeds runtime limits: ${id}`);
  const archive = zipFiles(files), hash = sha256(archive), name = `stk-${id}-${hash}.zip`;
  if (archive.length > maxBytes) throw new Error(`Archive exceeds runtime limit: ${id}`);
  const destination = join(output, name); writeFileSync(destination, archive);
  catalog.packs.push({ id, url: `${baseUrl}/${name}`, bytes: archive.length, sha256: hash,
    files: files.map((file) => ({ path: file.path, bytes: file.data.length, sha256: sha256(file.data) })) });
  for (const path of paths) catalog.owners[path] = id;
  publication.push({ name, path: destination, sha256: hash, bytes: archive.length });
}
writeFileSync(join(project, "modules/stk-car/game/src/resource-catalog.ts"), `// Generated by npm run prepare:packs. Immutable URLs and verified contents.\nimport type { ResourceCatalog } from "./resource-types.js";\nexport const resourceCatalog: ResourceCatalog = ${JSON.stringify(catalog)};\n`);
const startup = [...new Set([...core, "engineConfig.json", "stk-car.js", "asset-manifest.json", "startup-manifest.json"])].sort();
writeFileSync(join(assets, "startup-manifest.json"), `${JSON.stringify({ schemaVersion: 1, files: startup }, null, 2)}\n`);
writeFileSync(join(output, "publication.json"), `${JSON.stringify({ tag, files: publication }, null, 2)}\n`);
console.log(`Prepared ${catalog.packs.length} immutable runtime packs; startup includes ${startup.length} files`);
