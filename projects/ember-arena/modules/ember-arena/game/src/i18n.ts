export type MessageKey = keyof typeof messages;
export type MessageParameters = Readonly<Record<string, string | number | Message>>;
export interface Message { key: MessageKey; parameters?: MessageParameters }

export function normalizeLanguage(value: unknown): Language {
  return value === "zh-CN" || value === "zh" ? "zh-CN" : "en";
}

export function systemLanguage(locale: unknown): Language {
  return typeof locale === "string" && /^zh(?:[-_]|$)/i.test(locale.trim()) ? "zh-CN" : "en";
}

export function message(key: MessageKey, parameters?: MessageParameters): Message {
  return { key, parameters };
}

export function translate(language: Language, key: MessageKey, parameters: MessageParameters = {}): string {
  return messages[key][language === "zh-CN" ? 1 : 0].replace(/\{(\w+)\}/g, (placeholder, name: string) => {
    const value = parameters[name];
    return value === undefined ? placeholder : typeof value === "object" ? renderMessage(language, value) : `${value}`;
  });
}

export function renderMessage(language: Language, value: Message): string {
  return translate(language, value.key, value.parameters);
}
